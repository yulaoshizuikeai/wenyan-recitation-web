export function filterGoldenVerses(scope: string, search: string = ""): GoldenVerse[] {
  let list = CORE_GOLDEN_VERSES;
  if (scope === "GAOKAO72") {
    list = list.filter(v => v.isGaoKao72);
  } else if (scope === "BX_1") {
    list = list.filter(v => v.moduleId.startsWith("MODULE_BX_1"));
  } else if (scope === "BX_2") {
    list = list.filter(v => v.moduleId.startsWith("MODULE_BX_2"));
  } else if (scope === "XB_1") {
    list = list.filter(v => v.moduleId.startsWith("MODULE_XB_1"));
  } else if (scope === "XB_2") {
    list = list.filter(v => v.moduleId.startsWith("MODULE_XB_2"));
  } else if (scope === "XB_3") {
    list = list.filter(v => v.moduleId.startsWith("MODULE_XB_3"));
  } else if (scope === "XX") {
    list = list.filter(v => v.moduleId.startsWith("MODULE_XX"));
  }

  if (search.trim()) {
    const q = search.toLowerCase();
    list = list.filter(v =>
      v.verse.toLowerCase().includes(q) ||
      v.contextClue.toLowerCase().includes(q) ||
      v.articleTitle.toLowerCase().includes(q) ||
      v.author.toLowerCase().includes(q) ||
      v.scenarioTags.some(t => t.toLowerCase().includes(q))
    );
  }
  return list;
}
